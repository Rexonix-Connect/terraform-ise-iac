def json_schema_object(
    resource: Resource,
    lists: Tuple[str, ...],
    attrs: List[Dict[str, Any]],
    defaults: bool = False,
) -> Dict[str, Any]:
    """JSON Schema of a YAML object of a resource at a nested list path.

    For defaults, nested lists are a single object applied to each list item. The
    module applies defaults to the items of the resource's own nested lists only."""
    properties: Dict[str, Any] = {}
    for attr in attrs:
        description = attr.get("description", "")
        if attr["nested_attributes"] and defaults and lists:
            continue
        if attr["nested_attributes"]:
            item = json_schema_object(
                resource, lists + (attr["name"],), attr["nested_attributes"], defaults
            )
            schema = item if defaults else {"type": "array", "items": item}
        elif attr["type"] in ("List", "Set"):
            schema = {
                "type": "array",
                "items": {"type": JSON_TYPES.get(attr.get("element_type", "String"), "string")},
            }
        elif attr["type"] == "Map":
            schema = {"type": "object", "additionalProperties": {"type": "string"}}
        else:
            schema = {"type": JSON_TYPES.get(attr["type"], "string")}
            in_place = any(
                r.in_place and r.attr == attr["name"] and r.matches(lists)
                for r in resource.references
            )
            if "enum_values" in attr and not in_place:
                schema["enum"] = attr["enum_values"]
        if description:
            schema["description"] = description
        properties[attr["name"]] = schema
    if not lists and resource.rank_attribute:
        properties["rank"] = {
            "type": "integer",
            "description": resource.rank_attribute.get("description", "Rank"),
        }
    for ref in resource.references:
        if ref.in_place or not ref.matches(lists) or ref.name in properties:
            continue
        target = ref.target.replace("_", " ")
        properties[ref.name] = (
            {"type": "array", "items": {"type": "string"}, "description": f"Names of the referenced {target}"}
            if ref.comma_list
            else {"type": "string", "description": f"Name of the referenced {target}"}
        )
    schema = {"type": "object", "additionalProperties": False, "properties": properties}
    required = [k for k in resource.key if not lists and not defaults and k in properties]
    if required and not resource.singleton:
        schema["required"] = required
    return schema


def generate_schema_files(
    definitions: Dict[str, Any],
    resources: Dict[str, Resource],
    defaults_data: Dict[str, Any],
    provider_version: str,
    overrides: Dict[str, Any],
) -> None:
    """Generate the JSON Schema of the YAML model and the module model for tools"""
    comment = "Generated by gen/generate_module.py, do not edit."
    sections: Dict[str, Any] = {}
    default_sections: Dict[str, Any] = {}
    for resource in resources.values():
        item = json_schema_object(resource, (), resource.attributes)
        sections.setdefault(resource.category, {})[resource.name] = (
            item if resource.singleton else {"type": "array", "items": item}
        )
        default_sections.setdefault(resource.category, {})[resource.name] = json_schema_object(
            resource, (), resource.attributes, defaults=True
        )

    def section_schema(content: Dict[str, Any]) -> Dict[str, Any]:
        return {
            "type": "object",
            "additionalProperties": False,
            "properties": {
                section: {"type": "object", "additionalProperties": False, "properties": props}
                for section, props in sorted(content.items())
            },
        }

    json_schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": comment,
        "title": "terraform-ise-iac YAML model",
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "ise": section_schema(sections),
            "defaults": {
                "type": "object",
                "additionalProperties": False,
                "properties": {"ise": section_schema(default_sections)},
            },
        },
    }

    def model_attribute(attr: Dict[str, Any]) -> Dict[str, Any]:
        model = {
            "name": attr["name"],
            "type": attr["type"],
            "sensitive": attr["sensitive"],
            "write_only": bool(attr.get("write_only", False)),
        }
        for key in ("element_type", "enum_values", "mandatory", "model_name", "data_path"):
            if key in attr:
                model[key] = attr[key]
        if attr["nested_attributes"]:
            model["attributes"] = [model_attribute(a) for a in attr["nested_attributes"]]
        return model

    def api(definition: Dict[str, Any]) -> Dict[str, Any]:
        flags = (
            "id_path", "put_create", "post_update", "no_read", "no_delete", "no_import",
            "get_no_id", "put_no_id", "root_list", "data_source_name_query", "no_data_source",
        )
        info = {"rest_endpoint": definition.get("rest_endpoint")}
        info.update({k: definition[k] for k in flags if k in definition})
        # terraform import ID: references, identifying attributes, then the ID
        attrs = [ensure_name_in_attribute(dict(a)) for a in definition.get("attributes", [])]
        # values the provider always sends; they tell apart resources that share
        # an API path (e.g. RADIUS and TACACS allowed protocols)
        info["constants"] = [
            {"path": list(a.get("data_path", [])) + [a["model_name"]], "value": a["value"]}
            for a in attrs
            if "value" in a and "model_name" in a
        ]
        # without an ID path, the provider's object ID is the value of the first
        # identifying attribute (e.g. names of dictionaries and repositories)
        id_attr = next((a for a in attrs if a.get("id")), None)
        if (
            "id_path" not in definition
            and "put_id_query_path" not in definition
            and not str(definition.get("rest_endpoint", "")).startswith("/ers/")
            and id_attr
            and not id_attr.get("reference")
            and "model_name" in id_attr
        ):
            info["id_attribute"] = id_attr.get("response_data_path") or ".".join(
                list(id_attr.get("data_path", [])) + [id_attr["model_name"]]
            )
        if any(a.get("reference") for a in attrs):
            info["import_parts"] = [
                a["name"] for a in attrs if a.get("reference") or a.get("id")
            ] + ["id"]
        else:
            info["import_parts"] = ["id"]
        return info

    targets = {ref.target for r in resources.values() for ref in r.references}
    model = {
        "$comment": comment,
        "provider": {"source": "CiscoDevNet/ise", "version": provider_version},
        "self_reference_tiers": overrides.get("self_reference_tiers", 4),
        "id_regexp": "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$",
        "resources": {
            resource.name: {
                "category": resource.category,
                "terraform_type": f"ise_{resource.name}",
                "terraform_names": tier_resource_names(resource),
                "singleton": resource.singleton,
                "key": resource.key,
                "rank": resource.ranks,
                "attributes": [model_attribute(a) for a in resource.attributes],
                "defaults": defaults_data["defaults"]["ise"][resource.category].get(
                    resource.name, {}
                ),
                "references": [
                    {
                        "attr": ref.attr,
                        "lists": list(ref.lists),
                        "recursive": ref.recursive,
                        "target": ref.target,
                        "name": ref.name,
                        "when": ref.when,
                        "comma_list": ref.comma_list,
                        "in_place": ref.in_place,
                        "name_lookup": ref.name_lookup,
                    }
                    for ref in resource.references
                ],
                "api": api(resource.definition),
            }
            for resource in sorted(resources.values(), key=lambda r: r.name)
        },
        # objects referred to by name that the module does not create
        "lookup_only": {
            target: {"api": api(definitions[target])}
            for target in sorted(targets)
            if target not in resources
        },
    }

    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    for filename, content in ((JSON_SCHEMA_FILENAME, json_schema), (MODEL_FILENAME, model)):
        with (SCHEMA_DIR / filename).open("w") as f:
            json.dump(content, f, indent=2, sort_keys=False)
            f.write("\n")
        logger.info(f"Generated schema/{filename}")


def example_value(attr: Dict[str, Any], nested: bool = False) -> Any:
    """Example value of an attribute as found in the provider definitions.

    Nested lists are only filled at the first level, deeper levels have
    incomplete examples in the provider definitions."""
    if attr["type"] in ("List", "Set") and attr["nested_attributes"]:
        if nested:
            return None
        item = {
            n["name"]: example_value(n, nested=True)
            for n in attr["nested_attributes"]
            if example_value(n, nested=True) is not None
        }
        return [item] if item else None
    if attr["type"] in ("List", "Set"):
        return [attr["example"]] if "example" in attr else None
    if attr["type"] == "Map":
        if "example" not in attr:
            return None
        s = attr["example"].strip("{}").replace('"', "")
        k, v = [item.strip() for item in s.split("=")]
        return {k: v}
    if attr["type"] in ("String", "Int64", "Bool", "Float64"):
        return attr.get("example", None)
    logger.warning(f"Unsupported attribute type. {attr['name']} / {attr['type']}")
    return None


def generate_example_model_files(resources: Dict[str, Resource]) -> None:
    """Generate example model files based on definitions, group them by files as per doc_category"""

    # Example objects as defined by the provider
    examples: Dict[str, Dict[str, Any]] = {}
    for resource in resources.values():
        attributes = resource.attributes + (
            [resource.rank_attribute] if resource.rank_attribute else []
        )
        example = {
            attr["name"]: example_value(attr)
            for attr in attributes
            if example_value(attr) is not None
        }
        if "name" in resource.key and "name" not in example:
            example["name"] = resource.name.replace("_", " ").title().replace(" ", "")
        examples[resource.name] = example

    # resources sharing an API path (e.g. RADIUS and TACACS allowed protocols)
    # need different names, ISE rejects a second object with the same name
    names_by_endpoint: Dict[Tuple[Any, Any], str] = {}
    for resource in resources.values():
        example = examples[resource.name]
        if "name" not in example:
            continue
        endpoint = (resource.definition.get("rest_endpoint"), example["name"])
        if endpoint in names_by_endpoint:
            example["name"] = f"{example['name']}-{resource.name.rsplit('_', 1)[-1]}"
        names_by_endpoint[endpoint] = resource.name

    # Refer to other example objects by name where they are managed by the module,
    # so that the example is self-contained
    for resource in resources.values():
        example = examples[resource.name]
        for ref in resource.references:
            target = resources.get(ref.target)
            if ref.lists or target is None or target is resource:
                continue
            if any(example.get(k) != v for k, v in ref.when.items()):
                continue
            example.pop(ref.attr, None)
            target_name = examples[target.name]["name"]
            example[ref.name] = [target_name] if ref.comma_list else target_name

    # Group examples by category
    example_model_data: Dict[str, Dict[str, Any]] = {}
    for resource in resources.values():
        category = example_model_data.setdefault(resource.category, {})
        example = examples[resource.name]
        category[resource.name] = example if resource.singleton else [example]

    # Write example files
    for category, category_resources in example_model_data.items():
        generate_file(
            output_path=EXAMPLE_MODEL_DATA_DIR,
            filename=f"ise_{category}.yaml",
            output_yaml={"ise": {category: category_resources}},
        )


def is_valid_default(default: Any) -> bool:
    """Check if a default_value from the provider definitions is usable"""
    return default is not None and not (isinstance(default, str) and default.strip() == "")


def generate_defaults_data(resources: Dict[str, Resource]) -> Dict[str, Any]:
    """Generate default values for all resources, grouped by category. Only include attributes with valid default_value."""
    defaults_data: Dict[str, Dict[str, Any]] = {}
    for resource in resources.values():
        category = defaults_data.setdefault(resource.category, {})
        resource_object: Dict[str, Any] = {}
        for attr in resource.attributes:
            if attr["nested_attributes"]:
                # defaults applied to each item of a nested list
                nested_defaults = {
                    nested["name"]: nested["default_value"]
                    for nested in attr["nested_attributes"]
                    if is_valid_default(nested.get("default_value"))
                }
                if nested_defaults:
                    resource_object[attr["name"]] = nested_defaults
                continue
            default = attr.get("default_value", None)
            if not is_valid_default(default):
                continue  # skip attributes without valid default_value
            if attr["type"] in ("List", "Set"):
                resource_object[attr["name"]] = [default]
            elif attr["type"] == "Map":
                resource_object[attr["name"]] = {}
                if isinstance(default, str):
                    s = default.strip("{} ").replace('"', "")
                    if s and "=" in s:
                        k, v = [item.strip() for item in s.split("=")]
                        resource_object[attr["name"]][k] = v
            else:
                resource_object[attr["name"]] = default
        category[resource.name] = resource_object

    # Return finalized defaults data
    return {"defaults": {"ise": defaults_data}}


